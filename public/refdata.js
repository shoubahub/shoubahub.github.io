/* ===================================================================
   شعبة · البيانات المرجعية المشتركة
   مصدر واحد لكل القوائم المنسدلة (مناطق · مراحل · شعب · مواد · صفوف · حصص).
   لاحقاً تُدار من لوحة الإدارة (Super Admin)؛ الآن قيم معتمدة في الكود.

   ⚠ المواد أدناه **مبدئية قابلة للتعديل**: وُزّعت على صفوف كل مرحلة توزيعاً موحّداً
   ليكتمل شكل الشاشة، عدا «الفلسفة وعلم النفس» فهي معتمدة من المستخدم بدقّة.
   التعديل من هذا الملف الآن، ومن لوحة الإدارة لاحقاً.
   =================================================================== */
(function () {

  /* الصفوف لكل مرحلة — والمسارات لا تُذكر إلّا حيث توجد فعلاً */
  var GRADES = {
    'ابتدائي': [
      { grade:'الأول',   tracks:[] }, { grade:'الثاني', tracks:[] }, { grade:'الثالث', tracks:[] },
      { grade:'الرابع',  tracks:[] }, { grade:'الخامس', tracks:[] }
    ],
    'متوسط': [
      { grade:'السادس',  tracks:[] }, { grade:'السابع', tracks:[] },
      { grade:'الثامن',  tracks:[] }, { grade:'التاسع', tracks:[] }
    ],
    'ثانوي': [
      { grade:'العاشر',      tracks:['موحّد'] },
      { grade:'الحادي عشر',  tracks:['أدبي','علمي'] },
      { grade:'الثاني عشر',  tracks:['أدبي','علمي'] }
    ]
  };

  var names = function (stage) { return GRADES[stage].map(function (g) { return g.grade; }); };

  /* يوزّع مادّة على صفوف بمسار واحد */
  function on (name, grades, track) {
    return grades.map(function (g) { return { name: name, grade: g, track: track || '' }; });
  }
  /* يوزّع مادّة على صفوف الثانوي العليا بمساريها */
  function upperBoth (name) {
    return on(name, ['الحادي عشر','الثاني عشر'], 'أدبي')
      .concat(on(name, ['الحادي عشر','الثاني عشر'], 'علمي'));
  }
  /* الأساسية في الثانوي: العاشر موحّد + العليا بالمسارين */
  function core12 (name) {
    return on(name, ['العاشر'], 'موحّد').concat(upperBoth(name));
  }
  function flat (arr) { return [].concat.apply([], arr); }

  var BASIC = ['التربية الإسلامية','اللغة العربية','الرياضيات','العلوم','اللغة الإنجليزية','الاجتماعيات'];

  /* مواد المرحلتين الدنيا: المواد الأساسية على كل صفوف المرحلة (بلا مسارات) */
  function basicOf (stage) {
    var map = {};
    BASIC.forEach(function (s) { map[s] = on(s, names(stage)); });
    return map;
  }

  window.SHOUBA_REF = {

    /* المناطق التعليمية + القطاعات */
    regions: [
      'العاصمة','حولي','الفروانية','الأحمدي','الجهراء','مبارك الكبير',
      'التعليم الخاص','التعليم الديني','التربية الخاصة'
    ],

    stages: ['ابتدائي','متوسط','ثانوي'],

    /* الشُّعب (التخصّصات) لكل مرحلة */
    departments: {
      'ابتدائي': BASIC.slice(),
      'متوسط':   BASIC.slice(),
      'ثانوي':   ['الفلسفة وعلم النفس','اللغة العربية','التربية الإسلامية','الاجتماعيات','العلوم','الرياضيات','اللغة الإنجليزية']
    },

    /* المواد: المرحلة ← الشعبة ← [{ اسم · صف · مسار }]
       (فُهرست بالمرحلة لأن اسم الشعبة يتكرّر عبر المراحل بمواد مختلفة) */
    departmentSubjects: {
      'ابتدائي': basicOf('ابتدائي'),
      'متوسط':   basicOf('متوسط'),
      'ثانوي': {
        /* معتمدة من المستخدم بدقّة (2026-08-14) */
        'الفلسفة وعلم النفس': [
          { name:'تاريخ الكويت',        grade:'العاشر',      track:'موحّد' },
          { name:'علم النفس والاجتماع', grade:'الحادي عشر',  track:'أدبي' },
          { name:'الفلسفة',             grade:'الثاني عشر',  track:'أدبي' },
          { name:'الصحة النفسية',       grade:'الثاني عشر',  track:'أدبي وعلمي' },
          { name:'الدستور',             grade:'الثاني عشر',  track:'أدبي وعلمي' }
        ],
        'اللغة العربية':     core12('اللغة العربية'),
        'التربية الإسلامية': core12('التربية الإسلامية'),
        'اللغة الإنجليزية':  core12('اللغة الإنجليزية'),
        'الرياضيات':         core12('الرياضيات'),
        'العلوم': flat([
          on('العلوم', ['العاشر'], 'موحّد'),
          on('الفيزياء', ['الحادي عشر','الثاني عشر'], 'علمي'),
          on('الكيمياء', ['الحادي عشر','الثاني عشر'], 'علمي'),
          on('الأحياء',  ['الحادي عشر','الثاني عشر'], 'علمي'),
          on('الجيولوجيا', ['الثاني عشر'], 'علمي')
        ]),
        'الاجتماعيات': flat([
          on('التاريخ',   ['الحادي عشر','الثاني عشر'], 'أدبي'),
          on('الجغرافيا', ['الحادي عشر','الثاني عشر'], 'أدبي')
        ])
      }
    },

    /* بنية الصفوف والمسارات */
    gradesByStage: GRADES,

    /* نظام الحصص */
    periodsByStage: { 'ابتدائي':6, 'متوسط':7, 'ثانوي':7 },
    days: ['الأحد','الاثنين','الثلاثاء','الأربعاء','الخميس'],

    /* الأعوام الدراسية (الجاري أولاً) */
    years: ['٢٠٢٦/٢٠٢٧','٢٠٢٧/٢٠٢٨','٢٠٢٥/٢٠٢٦'],

    /* الفصول الدراسية */
    terms: ['الفصل الأول','الفصل الثاني'],

    /* «الحزمة الجاهزة لرئيس القسم» — سجلات رسمية بأسماء محايدة تصلح لكل تخصّص.
       مصدرها النماذج الرسمية الخمسة عشر؛ يُؤشّرها رئيس الشعبة ويزيد عليها وينقص. */
    readyRecords: [
      'تقرير زيارة الموجّه الفنّي',
      'تقرير زيارة رئيس الشعبة — سردي',
      'تقرير زيارة رئيس الشعبة — تقييمي',
      'جدول الزيارات الصفّية',
      'سجل اجتماعات الشعبة',
      'غلاف سجل متابعة المعلّم',
      'بطاقة متابعة معلّم',
      'متابعة سجلّات الإعداد',
      'متابعة الأعمال التحريرية',
      'ما قُطع من المنهج',
      'الملاحظات التربوية',
      'الدوام والاستئذانات الشهرية',
      'إنجازات المعلّم وأنشطته',
      'خطة متعلّم فائق',
      'خطة متعلّم متعثّر'
    ],

    /* مصدر واحد لقراءة مواد شعبة في مرحلة — تستعمله كل الشاشات */
    subjectsOf: function (stage, dept) {
      var byStage = this.departmentSubjects[stage] || {};
      return byStage[dept] || [];
    }
  };

})();
